
public class BitwiseOperator {

    public static void bitwiseand() {
        int a = 5;
        int b= 6;
        System.out.println(a&b);
        System.out.println(a|b);
        System.out.println(a^b);
        System.out.println(~6);
        System.out.println(5<<2);
    }

    public static void main(String [] args) {
        bitwiseand();
    }
}
